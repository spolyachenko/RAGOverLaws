HEAD = ("Ты — независимый судья качества ответов RAG-системы по вопросам российского "
        "законодательства. Оцени ОДИН критерий, строго по приведённой шкале.\n\n")
TAIL = ("\n\nОтвет: только JSON вида {\"score\": <число 1-5>, \"reason\": \"<1-2 предложения>\"}."
        )


def _judge_call(cl, model, prompt, key, cache):
    res, dt = ask(cl, model, prompt, key, cache)
    m = re.search(r"\{.*\}", res, re.S)
    try:
        d = json.loads(m.group() if m else res)
        s = int(d.get("score", 0))
    except (ValueError, AttributeError):
        s = 0
    return s, res[:200], dt


def main(mode):
    gold = {q["question"]: q for q in json.load(open(GOLD_FULL, encoding="utf-8"))}
    ans = json.load(open(DATA / "kt5_answers.json", encoding="utf-8"))
    import pandas as pd
    ck = pd.read_json(DATA / "chunks.jsonl", lines=True)
    ck_doc, ck_text = ck["doc"].tolist(), ck["text"].tolist()
    cl, model = client()
    cache = load_cache()

    qs = list(ans)
    if mode == "validate":
        # стратифицированная выборка 30: по типам, обязательно с negative (ветка «Не знаю»)
        by_t = {}
        for q in qs:
            by_t.setdefault(ans[q]["type"], []).append(q)
        plan = {"factual": 8, "composite": 8, "abstract": 7, "negative": 7}
        qs = [q for t in ("factual", "composite", "abstract", "negative")
              for q in by_t.get(t, [])[:plan[t]]]
        runs = ("j1:", "j2:")
    else:
        runs = ("jf:",)

    out = {}
    t0 = time.time()
    done = 0

    # все задачи (q, cfg, crit, run); 10 параллельных (sglang continuous batching)
    tasks = []
    for q in qs:
        a = ans[q]
        for cfg in ("baseline", "best"):
            ctx = "\n\n".join(
                f"[{i}] ({ck_doc[j]})\n{ck_text[j]}"
                for i, j in enumerate(a[cfg]["context_idx"], 1))
            for crit, body in CRITERIA.items():
                prompt = (HEAD + body + TAIL +
                          f"\nВопрос: {q}\n\nКонтекст:\n{ctx}\n\nОтвет системы: {a[cfg]['answer']}")
                for run in runs:
                    tasks.append((q, cfg, crit, run, prompt))

    def work(t):
        q, cfg, crit, run, prompt = t
        key = key_for(run + crit + cfg + ":", prompt)
        s, res, _ = _judge_call(cl, model, prompt, key, cache)
        return q, cfg, crit, run, s, res

    with ThreadPoolExecutor(max_workers=10) as ex:
        for q, cfg, crit, run, s, res in ex.map(work, tasks):
            out.setdefault(q, {}).setdefault(cfg, {}).setdefault(crit, {})[run.strip(":")] = {
                "score": s, "raw": res}
            done += 1
            if done % 100 == 0:
                print(f"{done}/{len(tasks)} ({time.time() - t0:.0f}s)", flush=True)
    save_cache(cache)
    suffix = "_val" if mode == "validate" else ""
    (DATA / f"kt5_judge{suffix}.json").write_text(
        json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"saved data/kt5_judge{suffix}.json")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "full")
